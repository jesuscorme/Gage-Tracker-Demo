"""Renderers for tabular reports (PDF, XLSX, CSV) with a common identification header."""

import csv
import io
from dataclasses import dataclass

from fpdf import FPDF
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

from app.modules.reports.definitions import Column

TEXT = {
    "es": {"generated": "Generado", "by": "por", "org": "Organización", "plant": "Planta", "all": "Todas",
           "filters": "Filtros", "rows": "Registros", "page": "Página", "yes": "Sí", "no": "No", "none": "Sin registros",
           "note": "Documento generado por Gage Tracker a partir de los registros vigentes en la fecha indicada."},
    "en": {"generated": "Generated", "by": "by", "org": "Organization", "plant": "Plant", "all": "All",
           "filters": "Filters", "rows": "Records", "page": "Page", "yes": "Yes", "no": "No", "none": "No records",
           "note": "Document generated by Gage Tracker from the records in force at the date shown."},
}


@dataclass
class Meta:
    code: str
    title: str
    organization: str
    plant: str | None
    generated_at: str
    generated_by: str
    filters: str
    lang: str


def cell(v, lang: str) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return TEXT[lang]["yes"] if v else TEXT[lang]["no"]
    s = str(v)
    if len(s) >= 19 and s[4] == "-" and s[10] == "T":     # ISO date-time -> "YYYY-MM-DD HH:MM"
        return s[:16].replace("T", " ")
    return s


def _lat(s: str) -> str:
    return s.encode("latin-1", "replace").decode("latin-1")


class _Pdf(FPDF):
    def __init__(self, meta: Meta):
        super().__init__(orientation="L", unit="mm", format="A4")
        self.meta = meta
        self.set_auto_page_break(auto=True, margin=14)
        self.alias_nb_pages()
        self.set_title(_lat(meta.title))

    def header(self):
        m, t = self.meta, TEXT[self.meta.lang]
        self.set_fill_color(18, 32, 51)
        self.rect(0, 0, 297, 16, style="F")
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 13)
        self.set_xy(10, 4)
        self.cell(190, 8, _lat(m.title))
        self.set_font("Helvetica", "", 8)
        self.set_xy(200, 4)
        self.cell(87, 4, _lat(m.code), align="R")
        self.set_xy(200, 8)
        self.cell(87, 4, _lat("GAGE TRACKER"), align="R")
        self.set_text_color(0, 0, 0)
        self.set_xy(10, 18)
        self.set_font("Helvetica", "", 8)
        self.cell(0, 4, _lat(f"{t['org']}: {m.organization}   |   {t['plant']}: {m.plant or t['all']}   |   "
                             f"{t['generated']}: {m.generated_at} {t['by']} {m.generated_by}"), new_x="LMARGIN", new_y="NEXT")
        if m.filters:
            self.cell(0, 4, _lat(f"{t['filters']}: {m.filters}"), new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def footer(self):
        t = TEXT[self.meta.lang]
        self.set_y(-10)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(90, 90, 90)
        self.cell(0, 4, _lat(f"{self.meta.code} · {t['note']}"), align="L")
        self.cell(0, 4, f"{t['page']} {self.page_no()}/{{nb}}", align="R")


def pdf(meta: Meta, columns: list[Column], rows: list[dict]) -> bytes:
    lang = meta.lang
    doc = _Pdf(meta)
    doc.add_page()
    labels = [getattr(c, lang) for c in columns]
    # Width proportional to the longest content (bounded), filling the printable width.
    raw = [max([len(lbl)] + [len(cell(r.get(c.key), lang)) for r in rows[:300]]) for c, lbl in zip(columns, labels)]
    raw = [min(max(w, 4), 40) for w in raw]
    total = 277
    widths = [total * w / sum(raw) for w in raw]
    doc.set_font("Helvetica", "B", 7)
    doc.set_fill_color(225, 230, 237)

    def head():
        for lbl, w in zip(labels, widths):
            doc.cell(w, 6, _lat(lbl)[: int(w / 1.5)], border=1, fill=True)
        doc.ln()

    head()
    doc.set_font("Helvetica", "", 7)
    if not rows:
        doc.cell(total, 6, _lat(TEXT[lang]["none"]), border=1)
        doc.ln()
    for i, r in enumerate(rows):
        if doc.get_y() > 190:
            doc.add_page()
            doc.set_font("Helvetica", "B", 7)
            head()
            doc.set_font("Helvetica", "", 7)
        fill = i % 2 == 1
        doc.set_fill_color(246, 248, 250)
        for c, w in zip(columns, widths):
            doc.cell(w, 5, _lat(cell(r.get(c.key), lang))[: int(w / 1.45)], border=1, fill=fill)
        doc.ln()
    doc.ln(2)
    doc.set_font("Helvetica", "B", 8)
    doc.cell(0, 5, _lat(f"{TEXT[lang]['rows']}: {len(rows)}"))
    return bytes(doc.output())


def xlsx(meta: Meta, columns: list[Column], rows: list[dict]) -> bytes:
    t = TEXT[meta.lang]
    wb = Workbook()
    ws = wb.active
    ws.title = "report"
    ws.append([meta.title])
    ws["A1"].font = Font(bold=True, size=14)
    for line in ([t["org"], meta.organization], [t["plant"], meta.plant or t["all"]],
                 [t["generated"], f"{meta.generated_at} {t['by']} {meta.generated_by}"], ["ID", meta.code],
                 [t["filters"], meta.filters or "—"], [t["rows"], len(rows)]):
        ws.append(line)
    ws.append([])
    header_row = ws.max_row + 1
    ws.append([getattr(c, meta.lang) for c in columns])
    for col in range(1, len(columns) + 1):
        c = ws.cell(row=header_row, column=col)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="122033")
        c.alignment = Alignment(wrap_text=True)
    for r in rows:
        ws.append([v if isinstance(v, (int, float)) and not isinstance(v, bool) else cell(v, meta.lang)
                   for v in (r.get(c.key) for c in columns)])
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    for i, c in enumerate(columns, start=1):
        ws.column_dimensions[ws.cell(row=header_row, column=i).column_letter].width = min(
            max(len(getattr(c, meta.lang)), *(len(cell(r.get(c.key), meta.lang)) for r in rows[:300]), 8) + 2, 50) \
            if rows else max(len(getattr(c, meta.lang)) + 2, 10)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def to_csv(meta: Meta, columns: list[Column], rows: list[dict]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([getattr(c, meta.lang) for c in columns])
    for r in rows:
        w.writerow([cell(r.get(c.key), meta.lang) for c in columns])
    return ("﻿" + buf.getvalue()).encode("utf-8")   # BOM so Excel opens UTF-8 correctly
